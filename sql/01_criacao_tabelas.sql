-- Trabalho Final — Modelagem de Banco de Dados
-- E-commerce de Eletronicos
-- Modelagem fisica: PostgreSQL / Supabase
-- Execute uma vez no SQL Editor de um projeto novo (schema public).
-- Nao apaga tabelas nem dados existentes.

BEGIN;

-- 1. Entidades independentes
CREATE TABLE public.cliente (
    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL,
    logradouro VARCHAR(150) NOT NULL,
    cep VARCHAR(9) NOT NULL,
    numero VARCHAR(15) NOT NULL,
    estado CHAR(2) NOT NULL,
    complemento VARCHAR(100),
    bairro VARCHAR(100) NOT NULL
);

CREATE TABLE public.funcionario (
    id_funcionario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    cargo VARCHAR(80) NOT NULL,
    salario NUMERIC(10,2) NOT NULL CHECK (salario >= 0),
    data_contratacao DATE NOT NULL
);

-- 2. Dados multivalorados e relacionamento 1:1
CREATE TABLE public.telefone_cliente (
    id_cliente INTEGER NOT NULL,
    telefone VARCHAR(20) NOT NULL,
    CONSTRAINT pk_telefone_cliente PRIMARY KEY (id_cliente, telefone),
    CONSTRAINT fk_telefone_cliente_cliente
        FOREIGN KEY (id_cliente) REFERENCES public.cliente(id_cliente)
        ON DELETE RESTRICT
);

CREATE TABLE public.cliente_conta (
    id_conta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INTEGER NOT NULL UNIQUE,
    data_criacao TIMESTAMPTZ NOT NULL DEFAULT now(),
    status VARCHAR(20) NOT NULL,
    ultimo_acesso TIMESTAMPTZ,
    CONSTRAINT fk_cliente_conta_cliente
        FOREIGN KEY (id_cliente) REFERENCES public.cliente(id_cliente)
        ON DELETE RESTRICT
);

-- 3. Produtos e compras (relacionamentos 1:N)
CREATE TABLE public.produto (
    id_produto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_funcionario INTEGER NOT NULL,
    nome VARCHAR(100) NOT NULL,
    descricao VARCHAR(255) NOT NULL,
    preco_venda NUMERIC(10,2) NOT NULL CHECK (preco_venda >= 0),
    quantidade_estoque INTEGER NOT NULL CHECK (quantidade_estoque >= 0),
    CONSTRAINT fk_produto_funcionario
        FOREIGN KEY (id_funcionario) REFERENCES public.funcionario(id_funcionario)
        ON DELETE RESTRICT
);

CREATE TABLE public.compra (
    id_compra INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INTEGER NOT NULL,
    data_compra DATE NOT NULL,
    valor_total NUMERIC(10,2) NOT NULL CHECK (valor_total >= 0),
    CONSTRAINT fk_compra_cliente
        FOREIGN KEY (id_cliente) REFERENCES public.cliente(id_cliente)
        ON DELETE RESTRICT
);

-- 4. Tabela associativa: Compra N:N Produto
CREATE TABLE public.item_compra (
    id_item_compra INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compra INTEGER NOT NULL,
    id_produto INTEGER NOT NULL,
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    preco_unitario NUMERIC(10,2) NOT NULL CHECK (preco_unitario >= 0),
    CONSTRAINT fk_item_compra_compra
        FOREIGN KEY (id_compra) REFERENCES public.compra(id_compra)
        ON DELETE RESTRICT,
    CONSTRAINT fk_item_compra_produto
        FOREIGN KEY (id_produto) REFERENCES public.produto(id_produto)
        ON DELETE RESTRICT
);

-- 5. Indices auxiliares para consultas e JOINs
CREATE INDEX idx_compra_cliente ON public.compra(id_cliente);
CREATE INDEX idx_produto_funcionario ON public.produto(id_funcionario);
CREATE INDEX idx_item_compra_compra ON public.item_compra(id_compra);
CREATE INDEX idx_item_compra_produto ON public.item_compra(id_produto);

-- 6. Protecao das tabelas contra acesso direto sem politicas pela Data API.
ALTER TABLE public.cliente ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.telefone_cliente ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cliente_conta ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.funcionario ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.produto ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.compra ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.item_compra ENABLE ROW LEVEL SECURITY;

COMMIT;
